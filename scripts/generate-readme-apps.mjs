#!/usr/bin/env node

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogueDirectory = path.join(root, "catalog", "apps");
const readmePath = path.join(root, "README.md");
const startMarker = "<!-- macify-apps:start -->";
const endMarker = "<!-- macify-apps:end -->";
const checkOnly = process.argv.slice(2).includes("--check");

function escapeTableCell(value) {
  return String(value)
    .replaceAll("\\", "\\\\")
    .replaceAll("|", "\\|")
    .replaceAll(/\r?\n/g, " ")
    .trim();
}

function pricingLabel(application) {
  const type = {
    free: "Free",
    freemium: "Freemium",
    paid: "Paid",
  }[application.pricingType];

  return application.pricingDetails
    ? `${type} · ${application.pricingDetails}`
    : type;
}

const applications = readdirSync(catalogueDirectory)
  .filter((fileName) => fileName.endsWith(".json"))
  .map((fileName) => JSON.parse(readFileSync(path.join(catalogueDirectory, fileName), "utf8")))
  .sort((left, right) => left.name.localeCompare(right.name, "en", { sensitivity: "base" }));

const rows = applications.map((application) => {
  const name = escapeTableCell(application.name);
  const description = escapeTableCell(application.tagline);
  const pricing = escapeTableCell(pricingLabel(application));
  return `| [${name}](https://macify.app/apps/${application.slug}) | ${description} | ${pricing} |`;
});

const generatedSection = [
  startMarker,
  "<!-- This table is generated by `npm run readme:generate`. Do not edit it by hand. -->",
  "| App | Description | Pricing |",
  "| --- | --- | --- |",
  ...rows,
  endMarker,
].join("\n");

const readme = readFileSync(readmePath, "utf8");
const startIndex = readme.indexOf(startMarker);
const endIndex = readme.indexOf(endMarker);

if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
  throw new Error("README.md must contain a valid generated application table section.");
}

const updatedReadme = `${readme.slice(0, startIndex)}${generatedSection}${readme.slice(endIndex + endMarker.length)}`;

if (checkOnly) {
  if (updatedReadme !== readme) {
    console.error("README.md application table is out of date. Run `npm run readme:generate`.");
    process.exitCode = 1;
  } else {
    console.log(`README.md application table is current (${applications.length} apps).`);
  }
} else {
  writeFileSync(readmePath, updatedReadme);
  console.log(`Updated README.md with ${applications.length} apps.`);
}
